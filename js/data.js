// 16. Xử lý logic sự kiện tìm kiếm trên thanh Header khi trang tải xong
document.addEventListener("DOMContentLoaded", () => {
  const searchForms = document.querySelectorAll(".header-search-form");

  searchForms.forEach((form) => {
    form.addEventListener("submit", (e) => {
      const input = form.querySelector(".header-search-input");
      // Nếu người dùng bấm tìm kiếm mà chưa nhập gì -> hiển thị hộp thoại prompt yêu cầu nhập
      if (!input.value.trim()) {
        e.preventDefault();
        const query = prompt("Nhập tên sản phẩm cần tìm kiếm:");
        if (query && query.trim() !== "") {
          // Chuyển hướng sang trang kết quả tìm kiếm kèm từ khóa đã mã hóa URL
          window.location.href = `search.html?q=${encodeURIComponent(query.trim())}`;
        }
      }
    });
  });
});
